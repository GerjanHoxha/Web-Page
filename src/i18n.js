export class I18nEngine {
  constructor() {
    this.currentLang = localStorage.getItem('k500_lang') || 'en';
  }

  setLang(lang) {
    if (!translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('k500_lang', lang);
    this.updatePageText();
  }

  updatePageText() {
    const dict = translations[this.currentLang];

    // Update text content
    document.querySelectorAll('[data-i18n]').forEach(elem => {
      const key = elem.getAttribute('data-i18n');
      if (dict[key]) {
        elem.textContent = dict[key];
      }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-ph]').forEach(elem => {
      const key = elem.getAttribute('data-i18n-ph');
      if (dict[key]) {
        elem.setAttribute('placeholder', dict[key]);
      }
    });

    // Toggle active lang buttons
    document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
    const activeBtn = document.getElementById(`lang-${this.currentLang}`);
    if (activeBtn) activeBtn.classList.add('active');
  }
}
